"""Download the public noise documents and verify them against their recorded SHA-256.

    python -m evaluation.rag_eval.fetch_public            # download missing files, verify all
    python -m evaluation.rag_eval.fetch_public --freeze   # curation only: (re)compute hashes and licence evidence

``public_sources.json`` is the curated list (URL, licence and the in-document proof of it).
``public_manifest.json`` is generated by ``--freeze`` and pins every document by SHA-256.
Downloaded files live in ``evaluation/corpus/public/`` and are never committed.
"""

import argparse
import json
import re
import time
import urllib.request
from datetime import date

from .corpus import CORPUS_DIR, CorpusFile, extract_text, sha256_file
from .text import norm

SOURCES = CORPUS_DIR / "public_sources.json"
MANIFEST = CORPUS_DIR / "public_manifest.json"
PUBLIC = CORPUS_DIR / "public"
HEADERS = {"User-Agent": "drivemind-eval-corpus/0.1 (licence-checked research use)"}
ARXIV_OAI = (
    "https://oaipmh.arxiv.org/oai?verb=GetRecord&identifier=oai:arXiv.org:{id}&metadataPrefix=arXiv"
)
PERMISSIVE_ARXIV = {
    "http://creativecommons.org/licenses/by/4.0/",
    "http://creativecommons.org/publicdomain/zero/1.0/",
}


def get(url: str, *, attempts: int = 4) -> bytes:
    for attempt in range(attempts):
        try:
            with urllib.request.urlopen(
                urllib.request.Request(url, headers=HEADERS), timeout=90
            ) as r:
                data: bytes = r.read()
                return data
        except Exception:
            if attempt == attempts - 1:
                raise
            time.sleep(10 * (attempt + 1))
    raise RuntimeError("unreachable")


def arxiv_license(arxiv_id: str) -> str | None:
    match = re.search(r"<license>([^<]*)</license>", get(ARXIV_OAI.format(id=arxiv_id)).decode())
    return match.group(1) if match else None


def freeze() -> None:
    sources = json.loads(SOURCES.read_text())["documents"]
    documents = []
    for source in sources:
        path = PUBLIC / source["filename"]
        if not path.exists():
            path.write_bytes(get(source["url"]))
            time.sleep(3)
        file = CorpusFile(f"public/{source['filename']}", "public", sha256_file(path), source)
        text = extract_text(file)
        if len(text) < 1500:
            raise ValueError(f"{source['filename']}: too little extractable text (scanned PDF?)")
        evidence = source.get("license_evidence")
        if evidence and norm(evidence) not in norm(text):
            raise ValueError(
                f"{source['filename']}: licence statement not found in the document text"
            )
        if source.get("arxiv_id"):
            found = arxiv_license(source["arxiv_id"])
            if found not in PERMISSIVE_ARXIV:
                raise ValueError(
                    f"{source['filename']}: arXiv licence {found!r} is not CC BY / CC0"
                )
            source = {**source, "license_url": found}
            time.sleep(4)
        elif not evidence:
            raise ValueError(f"{source['filename']}: needs license_evidence or arxiv_id")
        documents.append(
            {
                **source,
                "sha256": file.sha256,
                "bytes": path.stat().st_size,
                "chars": len(text),
                "verified_on": date.today().isoformat(),
            }
        )
    MANIFEST.write_text(json.dumps({"documents": documents}, indent=1, ensure_ascii=False) + "\n")
    print(f"froze {len(documents)} documents")


def fetch() -> None:
    PUBLIC.mkdir(parents=True, exist_ok=True)
    for entry in json.loads(MANIFEST.read_text())["documents"]:
        path = PUBLIC / entry["filename"]
        if not path.exists():
            path.write_bytes(get(entry["url"]))
            time.sleep(2)
        if sha256_file(path) != entry["sha256"]:
            raise SystemExit(
                f"{entry['filename']}: SHA-256 differs from the manifest (changed upstream?). "
                "Do not use it silently; re-freeze and re-review."
            )
    print("all public documents present and verified")


if __name__ == "__main__":
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--freeze", action="store_true")
    (freeze if parser.parse_args().freeze else fetch)()
