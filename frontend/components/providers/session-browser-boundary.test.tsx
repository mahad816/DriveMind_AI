import { act, cleanup, fireEvent, render, screen } from "@testing-library/react";
import { afterEach, expect, it, vi } from "vitest";
import { ApplicationSessionProvider } from "./application-session-provider";
import { ToastProvider } from "@/components/ui/toast-provider";
import { TooltipProvider } from "@/components/ui/tooltip";
import { AppShell } from "@/components/layout/app-shell";
import { apiFetch } from "@/lib/api/client";
const a = "00000000-0000-0000-0000-000000000065", b = "00000000-0000-0000-0000-000000000066";
const params = new URLSearchParams();
vi.mock("next/navigation", () => ({ usePathname: () => "/chat/legacy-a-chat", useSearchParams: () => params, useRouter: () => ({ replace: vi.fn(), push: vi.fn() }) }));
vi.mock("@/lib/hooks/use-knowledge-status", () => ({ useKnowledgeStatus: () => ({ setupState: "ready", isReady: true }) }));
vi.mock("@/components/layout/connection-banner", () => ({ ConnectionBanner: () => null }));
vi.mock("@/components/layout/mobile-header", () => ({ MobileHeader: () => null }));
const json = (body: unknown, status = 200) => new Response(JSON.stringify(body), { status, headers: { "Content-Type": "application/json" } });
const originalStorage = Object.getOwnPropertyDescriptor(window, "localStorage");
afterEach(() => { cleanup(); vi.unstubAllGlobals(); if (originalStorage) Object.defineProperty(window, "localStorage", originalStorage); });
it("A expiry then B verification cannot expose or adopt legacy browser conversations", async () => {
  const data: Record<string, string> = {};
  Object.defineProperty(window, "localStorage", { configurable: true, value: { getItem: (key: string) => data[key] ?? null, setItem: (key: string, value: string) => { data[key] = value; }, removeItem: (key: string) => { delete data[key]; } } });
  window.localStorage.setItem("drivemind:conversations", JSON.stringify([{ id: "legacy-a-chat", title: "SYNTHETIC_A_PRIVATE_TITLE", createdAt: "2026-01-01", updatedAt: "2026-01-01" }]));
  window.localStorage.setItem("drivemind:conversation-messages:legacy-a-chat", JSON.stringify([{ id: "turn-a", question: "A_QUESTION", status: "done", answer: "A_PRIVATE_ANSWER", citations: [] }]));
  const before = { ...data };
  let owner = a;
  const fetch = vi.fn().mockImplementation((url: string, _options?: RequestInit) => Promise.resolve(url.endsWith("/session") ? json({ kind: "GOOGLE_ACCOUNT", user_id: owner, csrf_token: "synthetic" }) : url.endsWith("/chat") && _options?.method === "POST" ? json({ user_id: owner, query_id: "synthetic-query", answer: "A_PRIVATE_MEMORY_ANSWER", citations: [], retrieval_count: 1, message: "synthetic" }) : json({ detail: "expired" }, 401)));
  vi.stubGlobal("fetch", fetch);
  render(<ToastProvider><TooltipProvider><ApplicationSessionProvider><AppShell><p>Legacy page children must not render</p></AppShell></ApplicationSessionProvider></TooltipProvider></ToastProvider>);
  await screen.findByText(/Saved conversations are temporarily unavailable/);
  expect(screen.queryByText(/SYNTHETIC_A_PRIVATE_TITLE|A_PRIVATE_ANSWER|Legacy page children/)).not.toBeInTheDocument();
  fireEvent.change(screen.getByRole("textbox", { name: "Message" }), { target: { value: "A synthetic question" } });
  fireEvent.click(screen.getByRole("button", { name: "Send message" }));
  await screen.findByText("A_PRIVATE_MEMORY_ANSWER");
  const chatCall = fetch.mock.calls.find(([url]) => url.endsWith("/chat"));
  expect(JSON.parse(String(chatCall?.[1]?.body ?? "{}"))).toEqual({ question: "A synthetic question" });
  await act(async () => { await expect(apiFetch("/files")).rejects.toMatchObject({ status: 401 }); });
  expect(await screen.findByRole("button", { name: "Sign in with Google" })).toBeInTheDocument();
  expect(screen.queryByText("A_PRIVATE_MEMORY_ANSWER")).not.toBeInTheDocument();
  owner = b; fireEvent(window, new Event("focus"));
  await screen.findByText(/Saved conversations are temporarily unavailable/);
  expect(screen.queryByText(/SYNTHETIC_A_PRIVATE_TITLE|A_PRIVATE_ANSWER/)).not.toBeInTheDocument();
  expect(screen.queryByText("A_PRIVATE_MEMORY_ANSWER")).not.toBeInTheDocument();
  expect(data).toEqual(before);
});
